int font_index(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= '0' && c <= '9') return 7 + (c - '0');
    if (c >= 'A' && c <= 'Z') return 17 + (c - 'A');
    switch (c) {
    case ' ': return 0;
    case '%': return 1;
    case '-': return 2;
    case '.': return 3;
    case '/': return 4;
    case ':': return 5;
    default:  return 6;   /* '?' */
    }
}
